const messagesByLocale: Record<SupportedLocale, Messages> = {
  "zh-CN": zhMessages,
  "en-US": enMessages,
};

type JoinKeys<T, Prefix extends string = ""> = {
  [K in keyof T & string]: T[K] extends string ? `${Prefix}${K}` : JoinKeys<T[K], `${Prefix}${K}.`>;
}[keyof T & string];

export type MessageKey = JoinKeys<Messages>;
type InterpolationValues = Record<string, string | number | boolean | null | undefined>;

function isSupportedLocale(value: string | null | undefined): value is SupportedLocale {
  return SUPPORTED_LOCALES.includes(value as SupportedLocale);
}

export function normalizeLocalePreference(
  value: string | null | undefined
): LocalePreference | null {
  if (value === "system" || isSupportedLocale(value)) return value;
  return null;
}

function localeFromLanguage(value: string): SupportedLocale | null {
  const normalized = value.trim().toLowerCase();
  if (!normalized) return null;
  if (normalized.startsWith("zh")) return "zh-CN";
  if (normalized.startsWith("en")) return "en-US";
  return null;
}

export function resolveLocale(
  preference: LocalePreference | null | undefined,
  systemLanguages: readonly string[] = []
): SupportedLocale {
  if (isSupportedLocale(preference)) return preference;

  for (const language of systemLanguages) {
    const locale = localeFromLanguage(language);
    if (locale) return locale;
  }

  return "zh-CN";
}

export function interpolateMessage(message: string, values: InterpolationValues = {}): string {
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, key: string) => {
    const value = values[key];
    return value === undefined || value === null ? placeholder : String(value);
  });
}

function messageAtPath(messages: Messages, key: MessageKey): string {
  const parts = key.split(".");
  let current: unknown = messages;
  for (const part of parts) {
    if (typeof current !== "object" || current === null || !(part in current)) {
      return key;
    }
    current = (current as Record<string, unknown>)[part];
  }
  return typeof current === "string" ? current : key;
}

export function createTranslator(locale: SupportedLocale) {
  return (key: MessageKey, values?: InterpolationValues): string =>
    interpolateMessage(messageAtPath(messagesByLocale[locale], key), values);
}

export function getSystemLanguages(): readonly string[] {
  if (typeof navigator === "undefined") return [];
  if (Array.isArray(navigator.languages) && navigator.languages.length > 0) {
    return navigator.languages;
  }
  return navigator.language ? [navigator.language] : [];
}

export function readStoredLocalePreference(): LocalePreference | null {
  return normalizeLocalePreference(getClientStorageItem(LOCALE_PREFERENCE_STORAGE_KEY));
}

function storeLocalePreference(preference: LocalePreference): void {
  setClientStorageItem(LOCALE_PREFERENCE_STORAGE_KEY, preference);
}

export function createDateTimeFormatters(locale: SupportedLocale, timeZone?: string) {
  const withTimeZone = <T extends Intl.DateTimeFormatOptions>(options: T): T =>
    timeZone ? { ...options, timeZone } : options;

  return {
    formatDate(value: Date | number | string, options: Intl.DateTimeFormatOptions = {}) {
      return new Intl.DateTimeFormat(locale, withTimeZone(options)).format(new Date(value));
    },
    formatTime(value: Date | number | string, options: Intl.DateTimeFormatOptions = {}) {
      return new Intl.DateTimeFormat(locale, withTimeZone(options)).format(new Date(value));
    },
    formatDateTime(value: Date | number | string, options: Intl.DateTimeFormatOptions = {}) {
      return new Intl.DateTimeFormat(locale, withTimeZone(options)).format(new Date(value));
    },
  };
}

interface I18nContextValue {
  locale: SupportedLocale;
  preference: LocalePreference;
  setPreference: (preference: LocalePreference) => void;
  t: ReturnType<typeof createTranslator>;
  formatDate: ReturnType<typeof createDateTimeFormatters>["formatDate"];
  formatTime: ReturnType<typeof createDateTimeFormatters>["formatTime"];
  formatDateTime: ReturnType<typeof createDateTimeFormatters>["formatDateTime"];
}

const I18nContext = React.createContext<I18nContextValue | null>(null);
const fallbackFormatters = createDateTimeFormatters("zh-CN");
const fallbackI18nContext: I18nContextValue = {
  locale: "zh-CN",
  preference: "system",
  setPreference: () => undefined,
  t: createTranslator("zh-CN"),
  ...fallbackFormatters,
};

export function I18nProvider({
  children,
  initialPreference,
}: {
  children: React.ReactNode;
  initialPreference?: LocalePreference;
}) {
  const [preference, setPreferenceState] = React.useState<LocalePreference>(
    () => initialPreference ?? readStoredLocalePreference() ?? "system"
  );
  const [systemLanguages, setSystemLanguages] =
    React.useState<readonly string[]>(getSystemLanguages);
  const locale = resolveLocale(preference, systemLanguages);

  React.useEffect(() => {
    setSystemLanguages(getSystemLanguages());
  }, []);

  React.useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = locale;
    }
  }, [locale]);

  const setPreference = React.useCallback((nextPreference: LocalePreference) => {
    storeLocalePreference(nextPreference);
    setPreferenceState(nextPreference);
  }, []);

  const value = React.useMemo<I18nContextValue>(() => {
    const translator = createTranslator(locale);
    const formatters = createDateTimeFormatters(locale);
    return {
      locale,
      preference,
      setPreference,
      t: translator,
      ...formatters,
    };
  }, [locale, preference, setPreference]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = React.useContext(I18nContext);
  return value ?? fallbackI18nContext;
}
